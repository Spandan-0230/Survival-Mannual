# I will just write a function that injects a block of code into the map initializations.
def inject(content, map_name, pairs):
    target = f"val {map_name} = mapOf("
    injection = ""
    for k, v in pairs:
        injection += f'\n        "{k}" to "{v}",'
    return content.replace(target, target + injection)

